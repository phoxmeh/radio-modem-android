package app.radiomodem.rig

import org.json.JSONArray
import org.json.JSONObject

data class RigMode(val name: String, val code: String, val sideband: String, val bwTable: String, val defaultBw: Int) {
    /** Filter-group key used for narrow-filter thresholds: SSB, CW, RTTY, DATA, or the mode name itself. */
    val group: String get() = when {
        name == "LSB" || name == "USB" -> "SSB"
        name.startsWith("CW") -> "CW"
        name.startsWith("RTTY") -> "RTTY"
        name.startsWith("DATA") -> "DATA"
        else -> name
    }
}

data class BwTable(val labels: List<String>, val values: List<Int>)
data class SerialSettings(val baud: Int, val stopBits: Int, val timeoutMs: Int, val postWriteDelayMs: Int, val rtscts: Boolean)

/**
 * Rig definition loaded from assets/rigs/<RIG>.json, generated by tools/flrig_extract.py from flrig's
 * rig classes plus a hand-written command spec. Command strings are templates (see [CatRig]).
 */
class RigProfile(val json: JSONObject) {
    val id: String = json.getString("id")
    val name: String = json.getString("name")
    val protocol: String = json.getString("protocol")
    /** No CAT link at all (a plain receiver): the app only hears the audio and keeps the frequency as a label. */
    val audioOnly: Boolean = json.optBoolean("audioOnly", false)
    val defaultFreq: Long = json.optLong("defaultFreq", 14070000)
    val serial: SerialSettings = json.getJSONObject("serial").let {
        SerialSettings(it.getInt("baud"), it.optInt("stopBits", 1), it.optInt("timeoutMs", 50),
            it.optInt("postWriteDelayMs", 0), it.optBoolean("rtscts", false))
    }
    val modes: List<RigMode> = json.getJSONArray("modes").objects().map {
        RigMode(it.getString("name"), it.getString("code"), it.getString("sideband"),
            it.getString("bwTable"), it.getInt("defaultBw"))
    }
    val bandwidths: Map<String, BwTable> = json.getJSONObject("bandwidths").let { o ->
        o.keys().asSequence().associateWith { k ->
            val t = o.getJSONObject(k)
            BwTable(t.getJSONArray("labels").strings(), t.getJSONArray("values").ints())
        }
    }
    fun bwTableFor(modeIdx: Int): BwTable? = modes.getOrNull(modeIdx)?.let { bandwidths[it.bwTable] }

    val terminator: Char = json.optString("terminator", ";").first()
    val minHz: Long = json.getJSONObject("frequency").optLong("minHz", 0)
    val maxHz: Long = json.getJSONObject("frequency").optLong("maxHz", 60_000_000)
    val powerMin: Int = json.getJSONObject("power").getInt("min")
    val powerMax: Int = json.getJSONObject("power").getInt("max")

    companion object {
        fun parse(text: String) = RigProfile(JSONObject(text))
    }
}

internal fun JSONArray.objects() = (0 until length()).map { getJSONObject(it) }
internal fun JSONArray.strings() = (0 until length()).map { getString(it) }
internal fun JSONArray.ints() = (0 until length()).map { getInt(it) }
